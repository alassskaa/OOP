package ru.nsu.sidorenko;

import java.util.Map;

/**
 * Интерфейс для работы с математическими выражениями, содержащими операции сложения,
 * вычитания, умножения, деления, числовые константы и переменные.
 * Основные возможности:
 *   Создание выражений: Используйте классы Number, Variable, Add,
 *   Sub, Mul, Div для создания выражений программно, или используйте
 *   ExpressionParser для создания из строки.
 *   Вычисление значений: Метод eval вычисляет значение выражения с заданными
 *   значениями переменных. Передайте карту с именами переменных и их значениями.
 *   Дифференцирование: Метод derivative вычисляет производную выражения
 *   по заданной переменной и возвращает новое выражение.
 *   Строковое представление: Метод toString возвращает строковое представление
 *   выражения в формате, аналогичном входному для парсинга.
 * Для разработчиков:
 * Для реализации нового типа выражения необходимо:
 *   Создать класс, реализующий интерфейс Expression.
 *   Реализовать метод toString для строкового представления выражения.
 *       Формат должен соответствовать формату парсера (все операции кроме констант и переменных
 *       должны быть заключены в скобки)
 *   Реализовать метод derivative для вычисления производной по заданной переменной.
 *       Метод должен возвращать новое выражение, представляющее производную исходного.
 *   Реализовать метод eval для вычисления значения выражения. Метод получает
 *       карту значений переменных и должен корректно обрабатывать случаи отсутствия переменной
 *       в карте.
 */
public interface Expression {
    
    /**
     * Возвращает строковое представление выражения.
     * 
     * @return строковое представление выражения
     */
    String toString();
    
    /**
     * Вычисляет производную данного выражения по заданной переменной.
     *
     * @param variable переменная, по которой требуется дифференцировать
     * @return новое выражение, представляющее производную
     */
    Expression derivative(String variable);
    
    /**
     * Вычисляет выражение с заданными значениями переменных.
     * 
     * @param arguments карта, содержащая имена переменных и их значения
     * @return вычисленный результат
     * @throws IllegalArgumentException если требуемая переменная отсутствует в карте arguments
     * @throws ArithmeticException если происходит деление на ноль или другая арифметическая ошибка
     */
    int eval(Map<String, Integer> arguments);
}
